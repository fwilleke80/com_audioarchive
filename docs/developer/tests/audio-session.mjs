/** @brief Verify iOS playback session acquisition, cooperation and restoration. */
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../../../pkg_audioarchive/com_audioarchive/media/js/audio-session.js', import.meta.url), 'utf8');
const {acquirePlaybackSession: acquire, releasePlaybackSession: release} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const session = {type: 'auto'};
Object.defineProperty(globalThis, 'navigator', {value: {audioSession: session}, configurable: true});
const player = Object.create(null);
const sampler = Object.create(null);
acquire(player);
assert.equal(session.type, 'playback');
acquire(player);
acquire(sampler);
release(player);
assert.equal(session.type, 'playback', 'pausing a clip must not mute a running sampler');
release(sampler);
assert.equal(session.type, 'auto', 'last release restores the previous category');
release(player);
assert.equal(session.type, 'auto');
acquire(sampler);
acquire(player);
release(sampler);
assert.equal(session.type, 'playback', 'leaving sampler mode must not mute a playing clip');
release(player);
session.type = 'play-and-record';
acquire(player);
assert.equal(session.type, 'play-and-record', 'an active microphone/call session is preserved');
release(player);
session.type = 'auto';
acquire(player);
session.type = 'play-and-record';
release(player);
assert.equal(session.type, 'play-and-record', 'external session changes are not overwritten on release');
Object.defineProperty(navigator, 'audioSession', {get() {throw new Error('Unavailable');}, configurable: true});
assert.doesNotThrow(() => acquire(player));
assert.doesNotThrow(() => release(player));
Object.defineProperty(navigator, 'audioSession', {value: undefined, configurable: true});
assert.doesNotThrow(() => acquire(player));
assert.doesNotThrow(() => release(player));
console.log('Audio-session ownership, restoration and unavailable-API checks passed.');
