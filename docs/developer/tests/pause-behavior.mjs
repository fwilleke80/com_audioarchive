/** @brief Exercise explicit Pause/Stop and rewind callbacks from the production player. */
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../../../pkg_audioarchive/com_audioarchive/media/js/player.js', import.meta.url),'utf8');
const callbacks = {};
const audio = {paused:false,currentTime:3,pause() {this.paused=true;},closest() {return player;}};
const player = {dataset:{pauseBehavior:'pause'},querySelector() {return {addEventListener(type,fn) {callbacks.rewind=fn;}};}};
const context = vm.createContext({audio,player,toggle:{addEventListener(type,fn) {callbacks.toggle=fn;}},updateCustomPlayerProgress() {},stopActive() {},async playNormalized() {audio.paused=false;}});
const start=source.indexOf("\t\t// @brief Rewind");
const end=source.indexOf('\n\t\tif (seek instanceof',start);
vm.runInContext(source.slice(start,end),context);
await callbacks.toggle();
assert.equal(audio.paused,true);
assert.equal(audio.currentTime,3,'Pause retains position');
await callbacks.toggle();
assert.equal(audio.paused,false);
assert.equal(audio.currentTime,3,'Resume retains position');
player.dataset.pauseBehavior='stop';
await callbacks.toggle();
assert.equal(audio.paused,true);
assert.equal(audio.currentTime,0,'Stop rewinds');
await callbacks.toggle();
assert.equal(audio.paused,false);
audio.currentTime=2;
callbacks.rewind();
assert.equal(audio.currentTime,0);
assert.equal(audio.paused,false,'Rewind preserves playing state');
audio.pause();audio.currentTime=2;
callbacks.rewind();
assert.equal(audio.paused,true,'Rewind preserves paused state');
audio.currentTime=2;audio.pause();
assert.equal(audio.currentTime,2,'Internal pause does not rewind');
console.log('Pause/resume, explicit Stop, and state-preserving rewind passed.');
